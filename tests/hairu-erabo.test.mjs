import { eraboFuda } from './_hairu.mjs';

let ng = 0, zen = 0;
const T = (na, ok, ji) => {
  zen++; if (!ok) ng++;
  console.log('  ' + (ok ? '✓' : '✗') + ' ' + na + (ok ? '' : '  — ' + (ji || '★思っていたのと 違う★')));
};

console.log('\n[hairu-erabo] ★『今 足した 人』の 札を 選ぶ 決め★');

/* ── ①② 束ね直された 形（★これが 本番で 起きて いる 形★） ───────── */
{
  /* ★部署で 束ねると 名簿の 番号は 飛びます★
     （営業＝0,2／未分類＝1 の ような 並び） */
  const taba = [
    { i: '0', na: '山田 太郎' },
    { i: '2', na: '従業員 3' },     /* ★今 足した 人（名簿の 最後）★ */
    { i: '1', na: '佐藤 花子' },
  ];
  const r = eraboFuda(taba);
  T('★★① 番号の 最大値で 当てる（2）★★', r.idx === '2' && r.na === '従業員 3',
    '出たのは ' + JSON.stringify(r));
  T('★★② 同じ 材料で『一番 下の 札』は 1（外れる）★★', r.shita === '1', '一番 下＝' + r.shita);
  T('★★② ＝前の 形なら ★他人（佐藤 花子）に 名前を 打ち込んで いた★★',
    taba[taba.length - 1].na === '佐藤 花子');
  T('★全 何枚か も 出す（分母）★', r.mai === 3, '枚数＝' + r.mai);
}

/* ── ③④ 足した 人が 画面に 出て いない ─────────────────── */
{
  /* ★絞り込み（退職者だけ 等）／描き直しの 遅れ★で ★足した 人が 出ない★ */
  const r = eraboFuda([{ i: '0', na: '山田 太郎' }, { i: '1', na: '佐藤 花子' }]);
  T('★★③ `従業員 N` が 無ければ 止める（未測定）★★',
    r.idx === null && /画面に 出て いない/.test(r.naze || ''), '出たのは ' + JSON.stringify(r));
  T('★★④ 止めた 時も 何を 見たか 出す★★', r.na === '佐藤 花子' && r.shita === '1',
    '出たのは ' + JSON.stringify(r));
}

/* ── 端（★材料が 無い／読めない★） ───────────────────── */
T('★札が 1枚も 無ければ 止める★', eraboFuda([]).idx === null);
T('★中身が 無い（null）でも 転ばない★', eraboFuda(null).idx === null);
T('★番号が 読めない 札だけなら 止める★', eraboFuda([{ i: 'x', na: '従業員 1' }]).idx === null);
T('★番号が 読めない 札は ★飛ばして★ 読める 物を 見る★',
  eraboFuda([{ i: 'x', na: '山田' }, { i: '7', na: '従業員 8' }]).idx === '7');
T('★名前の 前後の 余白は 落として 見る★', eraboFuda([{ i: '0', na: '  従業員 7  ' }]).idx === '0');
T('★名前が 空なら 止める★', eraboFuda([{ i: '0', na: '' }]).idx === null);
T('★`（無名）` でも 止める★', eraboFuda([{ i: '0', na: '（無名）' }]).idx === null);
/* ★番号は 字で 来ます（`getAttribute`）＝10 が 9 より 大きい 事を 見る★ */
T('★★番号は 数で 比べる（10 > 9）★★',
  eraboFuda([{ i: '9', na: '山田' }, { i: '10', na: '従業員 11' }]).idx === '10',
  '★字で 比べると 9 が 勝って しまいます★');

console.log('\n' + (ng ? '★' + ng + '件 おかしい（全 ' + zen + '通り）★' : '★' + zen + '通り ぜんぶ 思った通り★'));
